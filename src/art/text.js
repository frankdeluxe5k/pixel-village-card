// Pixel font and glyphs.
import { P, mk, tpl } from '../core/pixels.js';

export const FONT = {
  A: ['.###.', '#...#', '#...#', '#####', '#...#', '#...#', '#...#'],
  B: ['####.', '#...#', '#...#', '####.', '#...#', '#...#', '####.'],
  C: ['.###.', '#...#', '#....', '#....', '#....', '#...#', '.###.'],
  K: ['#...#', '#..#.', '#.#..', '##...', '#.#..', '#..#.', '#...#'],
  N: ['#...#', '##..#', '#.#.#', '#.#.#', '#..##', '#...#', '#...#'],
  O: ['.###.', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.'],
  S: ['.####', '#....', '#....', '.###.', '....#', '....#', '####.'],
  '!': ['##', '##', '##', '##', '##', '..', '##'],
};

export const GLYPHS = {
  z:     ['#####', '...#.', '..#..', '.#...', '#####'],
  note:  ['..#..', '..##.', '..#.#', '..#..', '.##..', '###..', '.#...'],
  heart: ['.##.##.', '#######', '#######', '.#####.', '..###..', '...#...'],
  bang:  ['##', '##', '##', '##', '..', '##'],
  dots:  ['##.##.##', '##.##.##'],
  mail:  ['#######', '##...##', '#.#.#.#', '#######'],
  box:   ['######', '#..#.#', '######', '#..#.#', '######'],
  coin:  ['..#..', '.####', '#.#..', '.###.', '..#.#', '####.', '..#..'],
  star:  ['..#..', '..#..', '#####', '.###.', '.#.#.'],
  cross: ['#...#', '.#.#.', '..#..', '.#.#.', '#...#'],
  q:     ['.###.', '#...#', '...#.', '..#..', '.....', '..#..'],
  spark: ['..#..', '..#..', '##.##', '..#..', '..#..'],
};

export function drawText(g, str, x, y, c) {
  for (const ch of str) {
    const gl = FONT[ch];
    tpl(g, gl, x, y, { '#': ch === '!' ? '#d03020' : c });
    x += gl[0].length + 1;
  }
}

// Glyphs (z's, notes, hearts, bubbles) with their drop shadow, one small sprite per glyph and colour.
export const glyphCache = new Map();
export function glyphSprite(name, c) {
  let m = glyphCache.get(name);
  if (!m) glyphCache.set(name, (m = new Map()));
  let cv = m.get(c);
  if (!cv) {
    const g = GLYPHS[name];
    cv = mk(g[0].length + 1, g.length + 1);
    const gg = cv.getContext('2d');
    tpl(gg, g, 1, 1, { '#': 'rgba(20,10,30,0.55)' });
    tpl(gg, g, 0, 0, { '#': c });
    if (name === 'heart') P(gg, 1, 1, 1, 1, '#ffffff');
    m.set(c, cv);
  }
  return cv;
}
